#!/usr/bin/env python3
"""Write docs/third-party-licenses.md from cargo metadata JSON.

The licence expression is copied from each crate's license field.
This script does not rewrite that text.
"""

import json
import sys

# SPDX ids treated as permissive. Anything else is listed for the owner.
# The expression in the table is still the crate's own string.
PERMISSIVE = {
    "0BSD",
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "BSL-1.0",
    "CC0-1.0",
    "ISC",
    "MIT",
    "MIT-0",
    "MPL-2.0",
    "Unicode-3.0",
    "Unicode-DFS-2015",
    "Unicode-DFS-2016",
    "Unlicense",
    "Zlib",
}
EXCEPTIONS = {"LLVM-exception"}


def split_top(expr, op):
    token = f" {op} "
    parts = []
    depth = 0
    buf = []
    i = 0
    while i < len(expr):
        char = expr[i]
        if char == "(":
            depth += 1
            buf.append(char)
            i += 1
        elif char == ")":
            depth = max(0, depth - 1)
            buf.append(char)
            i += 1
        elif depth == 0 and expr.startswith(token, i):
            parts.append("".join(buf).strip())
            buf = []
            i += len(token)
        else:
            buf.append(char)
            i += 1
    parts.append("".join(buf).strip())
    return [part for part in parts if part]


def is_permissive(expr):
    expr = expr.strip()
    if not expr:
        return False
    if expr.startswith("(") and expr.endswith(")"):
        return is_permissive(expr[1:-1].strip())
    ors = split_top(expr, "OR")
    if len(ors) > 1:
        return any(is_permissive(part) for part in ors)
    if "/" in expr and " " not in expr:
        return any(is_permissive(part) for part in expr.split("/"))
    ands = split_top(expr, "AND")
    if len(ands) > 1:
        return all(is_permissive(part) for part in ands)
    if " WITH " in expr:
        left, right = expr.split(" WITH ", 1)
        return left.strip() in PERMISSIVE and right.strip() in EXCEPTIONS
    return expr in PERMISSIVE


def normal_dep(dep):
    kinds = dep.get("dep_kinds") or []
    if not kinds:
        return True
    for kind in kinds:
        if kind.get("kind") in (None, "normal"):
            return True
    return False


def closure(meta):
    packages = {pkg["id"]: pkg for pkg in meta["packages"]}
    nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
    root_id = None
    for pkg in meta["packages"]:
        if pkg.get("name") == "pp-godot":
            root_id = pkg["id"]
            break
    if root_id is None or root_id not in nodes:
        raise SystemExit("licenses: pp-godot is not in cargo metadata")
    seen = set()
    stack = [root_id]
    while stack:
        current = stack.pop()
        for dep in nodes[current].get("deps", []):
            if not normal_dep(dep):
                continue
            pkg_id = dep["pkg"]
            if pkg_id == root_id or pkg_id in seen:
                continue
            seen.add(pkg_id)
            if pkg_id in nodes:
                stack.append(pkg_id)
    rows = []
    for pkg_id in seen:
        pkg = packages.get(pkg_id)
        if pkg is None:
            continue
        license_text = pkg.get("license")
        if license_text is None or str(license_text).strip() == "":
            license_text = None
        rows.append(
            {
                "name": pkg.get("name") or "",
                "version": pkg.get("version") or "",
                "license": license_text,
                "repository": pkg.get("repository") or "",
            }
        )
    rows.sort(key=lambda row: (row["name"].lower(), row["version"], row["repository"]))
    return rows


def table_cell(value):
    return value.replace("|", "\\|").replace("\n", " ")


def render(rows):
    lines = [
        "# Third-party Rust crates",
        "",
        "Generated by `./x licenses`.",
        "The command runs `cargo metadata --format-version 1 --locked`",
        "in the Steam Runtime toolbox, for the host triple, and keeps the",
        "normal dependency closure of `pp-godot` (the library shipped as",
        "`libpp_godot.so`). Dev-dependencies and build-dependencies are",
        "omitted. The licence column is the crate's `license` field, copied",
        "unchanged. A crate with no licence field is listed as missing.",
        "",
        "Godot's licence and its bundled notices are",
        "`licenses/GODOT-LICENSE.txt` and `licenses/GODOT-COPYRIGHT.txt`",
        "in an export, and are discussed in `docs/steam-release.md`.",
        "The art assets are credited in `docs/assets.md`, which `./x export`",
        "copies to `licenses/assets.md`.",
        "",
        "| Crate | Version | Licence | Repository |",
        "| --- | --- | --- | --- |",
    ]
    missing = []
    review = []
    for row in rows:
        if row["license"] is None:
            shown = "missing"
            missing.append(row)
        else:
            shown = row["license"]
            if not is_permissive(row["license"]):
                review.append(row)
        lines.append(
            "| {name} | {version} | {license} | {repository} |".format(
                name=table_cell(row["name"]),
                version=table_cell(row["version"]),
                license=table_cell(shown),
                repository=table_cell(row["repository"]),
            )
        )
    lines.append("")
    lines.append("## Needs a decision")
    lines.append("")
    if not missing and not review:
        lines.append("No crate in this list is missing a licence or outside the permissive set this file checks (MIT, Apache-2.0, BSD, ISC, Zlib, Unicode-DFS, MPL-2.0, CC0-1.0, Unlicense, BSL-1.0, 0BSD, and `OR` / `WITH LLVM-exception` combinations of those).")
    else:
        if missing:
            lines.append("Missing a `license` field:")
            lines.append("")
            for row in missing:
                lines.append(f"- {row['name']} {row['version']}")
            lines.append("")
        if review:
            lines.append("Licence expression is not in the permissive set above:")
            lines.append("")
            for row in review:
                lines.append(f"- {row['name']} {row['version']}: {row['license']}")
            lines.append("")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        print("usage: licenses.py METADATA.json OUT.md", file=sys.stderr)
        return 1
    with open(argv[1], encoding="utf-8") as handle:
        meta = json.load(handle)
    text = render(closure(meta))
    with open(argv[2], "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
